def compile_drawing(room, d):
    # Tiny authored offsets avoid exact half-pixel edge ties between Python
    # doubles and Godot's Vector2 floats. Apply to fill and its outline alike.
    nudged = {d.fills[i][0] for i in ({"LOC_BUILDING": [6], "LOC_VALLEY": [3]}.get(room, []))}
    def points(path):
        result = compiler.paths(path)
        if path in nudged:
            result = [[[round(x+.0625,5),y] for x,y in poly] for poly in result]
        return result
    regions = []
    for i, (path, color, hint) in enumerate(d.fills):
        polygon, = points(path)
        cells = compiler.interior(polygon)
        assert cells and polygon[0] == polygon[-1], (room, i)
        cell = min(cells, key=lambda n: ((n%736+.5-hint[0])**2 + (n//736+.5-hint[1])**2, n))
        regions.append(dict(id=f"region_{i:02}", polygon=polygon, color=color,
                            source_seed=list(hint), seed=[cell%736,cell//736],
                            raster_area=len(cells), mask_sha256=hashlib.sha256(b"".join(struct.pack("<i",n) for n in cells)).hexdigest()))
    lines = []
    for path, phase in d.strokes:
        for polyline in points(path):
            if len(polyline)>1:
                lines.append(dict(points=polyline,phase=phase,width=1.35 if phase=="detail" else 2.6))
    assert all(0 <= x <= 736 and 0 <= y <= 400 for line in lines for x,y in line['points']), room
    return dict(format="CAR-ART-002-experimental-v1", room=room, grid=[736,400],
                provenance="Original CAR-ART-004 / C — Línea solar; environmental background, human review pending.",
                background=d.p['paper'], ink=d.p['ink'], seconds=dict(contour=1.4,detail=.7,fill=1.4),
                lines=lines,regions=regions)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    if not args.check:
        OUT.mkdir(parents=True,exist_ok=True)
    for room, author in SCENES.items():
        data = compile_drawing(room,author())
        text = json.dumps(data,ensure_ascii=False,indent=2)+'\n'
        path = OUT / (room.lower()+'.json')
        if args.check:
            assert path.read_text(encoding='utf-8') == text, f"Generated art drift: {path}"
        else:
            path.write_text(text,encoding='utf-8')
        print(f"{room}: {len(data['lines'])} paths / {len(data['regions'])} regions")
    print('PASS: nine drawings' + (' deterministic' if args.check else ' compiled') + '; START, GRATE and legacy art untouched')


if __name__ == '__main__':
    main()
